#include "font_mid.c"

static uint16_t font_row[240];

/* draws s at (x, y); size2 is the size in half dots per pixel step: 2 = 1x, 3 = 1.5x, 4 = 2x. Characters outside the table
 * (and lower case) map to upper case or blank */
static void text_dots(uint32_t x, uint32_t y, const char *s, uint32_t size2, uint16_t fg, uint16_t bg)
{
    uint32_t n = 0, r, c, i, k, cell = 3u * size2, gw = (5u * size2 + 1u) / 2u, gh = (7u * size2 + 1u) / 2u;
    for (; s[n]; n++)
        ;
    for (r = 0; r < gh; r++) {
        uint32_t w = n * cell;
        if (w > 240u)
            w = 240u;
        for (i = 0; i < w; i++)
            font_row[i] = bg;
        for (c = 0; c < n; c++) {
            uint32_t ch = (uint8_t)s[c];
            if (ch >= 'a' && ch <= 'z')
                ch -= 32u;
            if (ch < 0x20u || ch > 0x5Au)
                ch = 0x20u;
            for (k = 0; k < gw; k++) {
                uint32_t px = c * cell + k;
                if (px < 240u && (FONT5X7[ch - 0x20u][k * 2u / size2] >> (r * 2u / size2)) & 1u)
                    font_row[px] = fg;
            }
        }
        {   /* RGB565 goes out big endian */
            static uint16_t sw[240];
            for (i = 0; i < w; i++)
                sw[i] = (uint16_t)((font_row[i] >> 8) | (font_row[i] << 8));
            lcd_blit(x, y + r, w, 1, sw);
            lcd_sync();                     /* sw is reused by the next row */
        }
    }
}

static void text5x7(uint32_t x, uint32_t y, const char *s, uint32_t scale, uint16_t fg, uint16_t bg)
{
    text_dots(x, y, s, 2u * scale, fg, bg);
}

/* The larger text: the Beiruti typeface (font_mid.c, generated by tools/gen_font_mid.py), 11 px high, anti-aliased (every pixel blends fg and
 * bg in 16 steps), proportional with the font's kerning pairs; upper and lower case (0x20..0x7E, other characters are blank).
 * A padded string (the pages pad texts with blanks to erase older, longer ones) still wipes n * 9 pixels, as when every character was 9 wide. */
static uint16_t mid_mix(uint16_t fg, uint16_t bg, uint32_t a)      /* a 0..15 of fg over bg, RGB565 */
{
    int32_t r0 = bg >> 11 & 31, g0 = bg >> 5 & 63, b0 = bg & 31, r1 = fg >> 11 & 31, g1 = fg >> 5 & 63, b1 = fg & 31, k = (int32_t)a;
    int32_t r = r0 + ((r1 - r0) * k + (k ? 7 : 0)) / 15, g = g0 + ((g1 - g0) * k + (k ? 7 : 0)) / 15, b = b0 + ((b1 - b0) * k + (k ? 7 : 0)) / 15;
    return (uint16_t)(r << 11 | g << 5 | b);
}

#define MID_MAXCH 40u                                   /* characters laid out at most (a 240 px line holds fewer) */

/* the pen position of each character of s (up to MID_MAXCH) into pos[], and the glyph index; returns the natural width in pixels */
static uint32_t mid_layout(const char *s, int32_t *pos, uint8_t *gl, uint32_t *count)
{
    int32_t x = 0;
    uint32_t n = 0, k;
    for (; s[n] && n < MID_MAXCH; n++) {
        uint32_t ch = (uint8_t)s[n];
        if (ch < 0x20u || ch > 0x7Eu)
            ch = 0x20u;
        if (n) {
            uint32_t prev = 0x20u + gl[n - 1u];
            for (k = 0; k < FONT_MID_NKERN; k++)
                if (FONT_MID_KERN[k][0] == (int8_t)prev && FONT_MID_KERN[k][1] == (int8_t)ch) {
                    x += FONT_MID_KERN[k][2];
                    break;
                }
        }
        gl[n] = (uint8_t)(ch - 0x20u);
        pos[n] = x;
        x += FONT_MID_ADV[ch - 0x20u];
    }
    *count = n;
    return (uint32_t)(x > 0 ? x : 0);
}

static uint32_t text_mid_w(const char *s)               /* the width of s in pixels */
{
    int32_t pos[MID_MAXCH];
    uint8_t gl[MID_MAXCH];
    uint32_t n;
    return mid_layout(s, pos, gl, &n);
}

/* draws s at (x, y); the field wiped is at least `field` pixels wide */
static void text_mid_field(uint32_t x, uint32_t y, const char *s, uint16_t fg, uint16_t bg, uint32_t field)
{
    uint16_t lut[16];
    int32_t pos[MID_MAXCH];
    uint8_t gl[MID_MAXCH];
    uint32_t n, nat = mid_layout(s, pos, gl, &n), r, c, i, w;
    for (i = 0; i < 16u; i++) {                         /* the 16 shades, already byte swapped for the LCD */
        uint16_t m = mid_mix(fg, bg, i);
        lut[i] = (uint16_t)((m >> 8) | (m << 8));
    }
    w = nat > field ? nat : field;
    if (w > 240u - x)
        w = 240u - x;
    if (!w)
        return;
    for (r = 0; r < FONT_MID_H; r++) {
        static uint16_t sw[240];
        static uint8_t al[240];
        for (i = 0; i < w; i++)
            al[i] = 0;
        for (c = 0; c < n; c++) {
            const uint8_t *g = &FONT_MID[gl[c]][r * FONT_MID_GW];
            uint32_t k;
            for (k = 0; k < FONT_MID_GW; k++) {
                int32_t px = pos[c] - (int32_t)FONT_MID_ORG + (int32_t)k;
                if (g[k] > 0u && px >= 0 && px < (int32_t)w && g[k] > al[px])   /* neighbours' margins may overlap: the brighter shade wins */
                    al[px] = g[k];
            }
        }
        for (i = 0; i < w; i++)
            sw[i] = lut[al[i]];
        lcd_blit(x, y + r, w, 1, sw);
        lcd_sync();                                     /* sw is reused by the next row */
    }
}

static void text_mid(uint32_t x, uint32_t y, const char *s, uint16_t fg, uint16_t bg)
{
    uint32_t n = 0;
    for (; s[n]; n++)
        ;
    text_mid_field(x, y, s, fg, bg, n * FONT_MID_W);
}
