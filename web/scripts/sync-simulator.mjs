// Copies a built fm1-emu page (https://github.com/joakimeriksson/fm1-emu, MIT, by Joakim Eriksson: the FM-1's CPU, screen, keys, knobs and
// audio in WebAssembly) into public/sim/, where the Simulator tab loads it, and writes its firmware catalog: this app's own package.
// Use tools/build_simulator.sh, which builds the emulator and calls this. Run from web/:
//   node scripts/sync-simulator.mjs EMU_DIST [EMU_CHECKOUT]     (EMU_DIST: the web/dist of the emulator's web/build.sh)
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { join, resolve } from 'node:path';

const [distArg, checkoutArg] = process.argv.slice(2);
if (!distArg) {
  console.error('usage: node scripts/sync-simulator.mjs EMU_DIST [EMU_CHECKOUT]');
  process.exit(1);
}
const dist = resolve(distArg);
const out = new URL('../public/sim/', import.meta.url);
mkdirSync(out, { recursive: true });
for (const f of ['index.html', 'style.css', 'main.js', 'persistence.js', 'worklet.js', 'jit.js', 'fwsc.js', 'fm1_web.wasm']) {
  if (!existsSync(join(dist, f))) {
    console.error(`${join(dist, f)} is missing: build the emulator first (its web/build.sh)`);
    process.exit(1);
  }
  copyFileSync(join(dist, f), new URL(f, out));
}
let commit = '';
if (checkoutArg) {
  const checkout = resolve(checkoutArg);
  copyFileSync(join(checkout, 'LICENSE'), new URL('LICENSE-fm1-emu-MIT.txt', out));
  commit = execFileSync('git', ['-C', checkout, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
}
writeFileSync(
  new URL('SOURCE.txt', out),
  `The page, scripts and fm1_web.wasm here are the web build of fm1-emu by Joakim Eriksson, MIT (LICENSE-fm1-emu-MIT.txt):\n` +
    `https://github.com/joakimeriksson/fm1-emu${commit ? ` at commit ${commit}` : ''}\n` +
    `Built with that repository's web/build.sh and copied here by web/scripts/sync-simulator.mjs (tools/build_simulator.sh).\n` +
    `firmwares.json is this app's own catalog: the package it runs is ../firmware/modular-1.fwsc.\n`,
);
const meta = JSON.parse(readFileSync(new URL('../public/firmware/modular-1.json', import.meta.url), 'utf8'));
writeFileSync(
  new URL('firmwares.json', out),
  JSON.stringify(
    {
      note: 'Generated by web/scripts/sync-simulator.mjs: the one firmware this app bundles.',
      default: 'modular-1',
      firmwares: [
        {
          id: 'modular-1',
          name: 'Modular-1',
          version: meta.version,
          author: 'morgulbrut',
          license: 'GPL-3.0-only',
          about: 'A Nord Modular style patchable synth: two patch voices, a drum machine, arpeggiators, a mixer and a settings menu.',
          repo: 'https://github.com/WiggisModular/Modular-1',
          package: '../firmware/modular-1.fwsc',
        },
      ],
    },
    null,
    1,
  ) + '\n',
);
console.log(`public/sim/: fm1-emu ${commit.slice(0, 7) || '(commit unknown)'}, firmware ${meta.version}`);
