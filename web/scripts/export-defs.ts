// Writes firmware/src/defs.h (module definitions for the C engine) and firmware/src/presets.h (the factory
// patches as binary). Run from web/:  npx vite-node scripts/export-defs.ts
import { writeFileSync } from 'node:fs';
import { DEFS, DELAY_DIVS, DELAY_CLK_PPQN } from '../src/modules';
import { encodePatch, TYPE_ORDER, toQ16 } from '../src/patchbin';
import { PRESETS } from '../src/presets';

const up = (s: string): string => s.toUpperCase().replace(/[^A-Z0-9]/g, '_');
const L: string[] = [];
const w = (s = ''): number => L.push(s);

w('/* SPDX-License-Identifier: GPL-3.0-only */');
w('/* Generated by web/scripts/export-defs.ts from web/src/modules.ts. Do not edit. */');
w('#pragma once');
w('#include <stdint.h>');
w();
w(`#define N_TYPES ${TYPE_ORDER.length}`);
w('enum {');
for (const t of TYPE_ORDER) w(`    T_${up(t)},`);
w('};');
w();
for (const t of TYPE_ORDER) {
  const d = DEFS[t];
  const explicit = d.inputs.filter((i) => !i.pin);
  w(`/* ${t}: ${d.label} */`);
  d.inputs.forEach((p, i) => w(`#define ${up(t)}_I_${up(p.name)} ${i}`));
  d.outputs.forEach((p, i) => w(`#define ${up(t)}_O_${up(p.name)} ${i}`));
  d.params.forEach((p, i) => w(`#define ${up(t)}_P_${up(p.name)} ${i}`));
  w(`#define ${up(t)}_NIN ${d.inputs.length}`);
  w(`#define ${up(t)}_NOUT ${d.outputs.length}`);
  w(`#define ${up(t)}_NPAR ${d.params.length}`);
  w(`#define ${up(t)}_CVBASE ${d.paramInputs ? explicit.length : -1}`);   /* index of p1; p2 follows */
  w();
}
w(`#define DELAY_NDIV ${DELAY_DIVS.length}`);
w(`#define DELAY_CLK_PPQN ${DELAY_CLK_PPQN}`);
w(`static const uint8_t DELAY_DIV_NUM[DELAY_NDIV] = {${DELAY_DIVS.map((d) => d.num).join(', ')}};`);
w(`static const uint8_t DELAY_DIV_DEN[DELAY_NDIV] = {${DELAY_DIVS.map((d) => d.den).join(', ')}};`);
w(`static const char *const DELAY_DIV_NAME[DELAY_NDIV] = {${DELAY_DIVS.map((d) => `"${d.name}"`).join(', ')}};`);
w();
const maxOf = (f: (t: string) => number): number => Math.max(...TYPE_ORDER.map(f));
w(`#define MAX_IN ${maxOf((t) => DEFS[t].inputs.length)}`);
w(`#define MAX_OUT ${maxOf((t) => DEFS[t].outputs.length)}`);
w(`#define MAX_PAR ${maxOf((t) => DEFS[t].params.length)}`);
w();
w('typedef struct {');
w('    uint8_t nin, nout, npar;');
w('    int8_t cvbase;          /* index of the p1 input (p2 follows), -1: the module has no parameter inputs */');
w('    const int32_t *pmin, *pmax, *pdef, *pinc;   /* Q16.16; pinc: what one knob click adds */');
w('    const char *name;       /* upper case, for the LCD */');
w('    const char *const *pname;');
w('    const char *const *inname;              /* input names, upper case */');
w('    const uint8_t *plog;                    /* 1: a logarithmic parameter, 2: logarithmic and bent (the filter cutoff) */');
w('    const char *const *punit;               /* "HZ", "ST", ... or "" */');
w('    const char *const *const *pchoice;      /* per parameter: the names of a choice parameter (0-terminated), or 0 */');
w('} def_t;');
w();
for (const t of TYPE_ORDER) {
  const ps = DEFS[t].params;
  w(`static const char *const ${up(t)}_INNAMES[] = {${DEFS[t].inputs.map((p) => `"${p.name.toUpperCase()}"`).join(', ') || '0'}};`);
  if (!ps.length) continue;
  const row = (f: (p: (typeof ps)[number]) => number): string => ps.map((p) => toQ16(f(p))).join(', ');
  w(`static const int32_t ${up(t)}_MIN[] = {${row((p) => p.min)}};`);
  w(`static const int32_t ${up(t)}_MAX[] = {${row((p) => p.max)}};`);
  w(`static const int32_t ${up(t)}_DEF[] = {${row((p) => p.default)}};`);
  w(`static const int32_t ${up(t)}_INC[] = {${row((p) => Math.max(p.step ?? 0, (p.max - p.min) / 100))}};`);
  w(`static const char *const ${up(t)}_PN[] = {${ps.map((p) => `"${p.name.toUpperCase()}"`).join(', ')}};`);
  w(`static const uint8_t ${up(t)}_LOG[] = {${ps.map((p) => (p.log ? (p.bend ? 2 : 1) : 0)).join(', ')}};`);
  w(`static const char *const ${up(t)}_UNIT[] = {${ps.map((p) => `"${(p.unit ?? '').toUpperCase()}"`).join(', ')}};`);
  ps.forEach((p, i) => {
    if (p.choices) w(`static const char *const ${up(t)}_CH${i}[] = {${p.choices.map((c) => `"${c.toUpperCase()}"`).join(', ')}, 0};`);
  });
  w(`static const char *const *const ${up(t)}_CH[] = {${ps.map((p, i) => (p.choices ? `${up(t)}_CH${i}` : '0')).join(', ')}};`);
}
w();
w('static const def_t DEFS[N_TYPES] = {');
for (const t of TYPE_ORDER) {
  const d = DEFS[t];
  const has = d.params.length > 0;
  const n = up(t);
  w(`    {${n}_NIN, ${n}_NOUT, ${n}_NPAR, ${n}_CVBASE, ${has ? `${n}_MIN, ${n}_MAX, ${n}_DEF, ${n}_INC` : '0, 0, 0, 0'}, "${d.label.toUpperCase()}", ${has ? `${n}_PN` : '0'}, ${n}_INNAMES, ${has ? `${n}_LOG, ${n}_UNIT, ${n}_CH` : '0, 0, 0'}},   /* ${t} */`);
}
w('};');
w();
writeFileSync(new URL('../../firmware/src/defs.h', import.meta.url), L.join('\n'));

const P: string[] = ['/* SPDX-License-Identifier: GPL-3.0-only */', '/* Generated by web/scripts/export-defs.ts from the JSON files in web/presets. Do not edit. */', '#pragma once', '#include <stdint.h>', ''];
const names = Object.keys(PRESETS);
names.forEach((n, i) => {
  const bin = encodePatch(PRESETS[n]());
  P.push(`static const uint8_t PRESET_${i}[${bin.length}] = {${Array.from(bin).join(',')}};   /* ${n} */`);
});
P.push('', `#define N_PRESETS ${names.length}`);
P.push('static const struct { const char *name; const uint8_t *data; uint32_t len; } PRESET_LIST[N_PRESETS] = {');
names.forEach((n, i) => P.push(`    {"${n.toUpperCase()}", PRESET_${i}, sizeof PRESET_${i}},`));
P.push('};', '');
writeFileSync(new URL('../../firmware/src/presets.h', import.meta.url), P.join('\n'));
console.log('wrote defs.h, presets.h');
