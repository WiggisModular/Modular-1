"""Render the LCD's larger font (firmware/src/font_mid.c) from the Beiruti typeface.

  nix develop -c python3 -I tools/gen_font_mid.py Beiruti.ttf [--preview out.png]

Beiruti (c) 2024 The Beiruti Project Authors, SIL Open Font License 1.1 (LICENSES/OFL-1.1-Beiruti.txt), from
https://github.com/googlefonts/beiruti (download: https://file.openfont.org/archive/beiruti.zip). The output is the
glyphs ASCII 0x20..0x7E (upper and lower case) as 16-level anti-aliased bitmaps, 11 rows high, with a proportional advance
width per glyph and the font's own kerning pairs (from its GPOS table through Pillow's Raqm layout, rounded to whole pixels).
Capitals and ascenders fill rows 0..8, the baseline is at row 9, so descenders (g j p q y) have 2 rows and are cut one row
short. Needs Pillow with Raqm.
"""
import sys
from PIL import Image, ImageDraw, ImageFont

GW, CH = 12, 11             # a glyph bitmap: 12 columns (the pen is at column 1: a few glyphs reach left of it), 11 rows
ORG = 1                     # the pen's column in the bitmap
SIZE, WEIGHT = 14, 700      # pixel size of the em, the variable font's weight (Bold)
BASE = 9                    # baseline row: capitals fill rows 0..8, descenders get rows 9 and 10 (a third row is cut off)
TRACK = 1                   # extra pixels between glyphs: the bold weight at 14 px is too tight otherwise
SPACE = 5                   # the width of a blank
FIRST, LAST = 0x20, 0x7E
MID_W = 9                   # the old fixed cell: pages pad strings to a number of characters, so a field is at least n * 9 wide


def font(path):
    ft = ImageFont.truetype(path, SIZE, layout_engine=ImageFont.Layout.RAQM)
    ft.set_variation_by_axes([WEIGHT])
    return ft


def glyphs(ft):
    out, adv = [], []
    for code in range(FIRST, LAST + 1):
        c = chr(code)
        im = Image.new("L", (GW, CH), 0)
        if c == " ":
            adv.append(SPACE)
        else:
            bb = ft.getbbox(c, anchor="ls")
            lb = min(0, bb[0])                                       # ink left of the pen (j): move the glyph right, widen its advance
            ImageDraw.Draw(im).text((ORG - lb, BASE), c, font=ft, fill=255, anchor="ls")
            adv.append(max(round(ft.getlength(c)), bb[2]) + TRACK - lb)     # the font's advance, at least the ink, and the tracking
        out.append([min(15, (v + 8) * 15 // 255) for v in im.tobytes()])
    return out, adv


def kerning(ft, adv):
    """pairs (a, b, pixels) where the font moves b towards a (negative) or away, beyond the plain advances"""
    pairs = []
    for a in range(FIRST + 1, LAST + 1):
        for b in range(FIRST + 1, LAST + 1):
            d = ft.getlength(chr(a) + chr(b)) - ft.getlength(chr(a)) - ft.getlength(chr(b))
            k = round(d)
            if k:
                pairs.append((a, b, max(-3, min(3, k))))
    return pairs


def preview(g, adv, kern, text, path):
    k = {(a, b): d for a, b, d in kern}
    img = Image.new("L", (240, CH * 4), 0)
    for row, line in enumerate(text):
        x = 0
        for n, ch in enumerate(line):
            c = ord(ch) - FIRST
            if n:
                x += k.get((ord(line[n - 1]), ord(ch)), 0)
            for i, v in enumerate(g[c]):
                px = x - ORG + i % GW
                if 0 <= px < 240 and v:
                    img.putpixel((px, row * CH + i // GW), max(img.getpixel((px, row * CH + i // GW)), v * 17))
            x += adv[c]
    img.resize((img.width * 4, img.height * 4), Image.NEAREST).save(path)


def main():
    a = sys.argv[1:]
    if not a:
        sys.exit(__doc__)
    ft = font(a[0])
    g, adv = glyphs(ft)
    kern = kerning(ft, adv)
    if "--preview" in a:
        preview(g, adv, kern, ["Cool Filter 24 dB  Master 90%", "Maj Pentatonic (6) AVATAR Type", "NOISE RHYTHM quickly gypsy WAVE", "Bright Saw 0.50 Hz  Tune To Ty"], a[a.index("--preview") + 1])
    lines = [
        "/* SPDX-License-Identifier: GPL-3.0-only",
        " * Copyright (C) 2026 morgulbrut */",
        "/* GENERATED by tools/gen_font_mid.py: do not edit. The larger text font: the Beiruti typeface, rendered as 16-level",
        " * anti-aliased bitmaps (one byte per pixel, 0..15), ASCII 0x20..0x7E, 11 rows, proportional (FONT_MID_ADV) with kerning pairs",
        " * (FONT_MID_KERN: left char, right char, pixels). Beiruti: Copyright 2024 The Beiruti Project Authors",
        " * (https://github.com/googlefonts/beiruti), SIL Open Font License 1.1, see LICENSES/OFL-1.1-Beiruti.txt. These bitmaps are a",
        " * modified version of the font software (rendered at a fixed size and weight, spacing taken from the font). */",
        f"#define FONT_MID_GW {GW}u              /* bitmap columns of a glyph */",
        f"#define FONT_MID_ORG {ORG}u             /* the pen's column in it */",
        f"#define FONT_MID_H {CH}u",
        f"#define FONT_MID_W {MID_W}u              /* the old fixed cell: a padded string's field is at least this wide a character */",
        f"static const uint8_t FONT_MID_ADV[{LAST - FIRST + 1}] = {{" + ",".join(map(str, adv)) + "};",
        f"static const int8_t FONT_MID_KERN[][3] = {{",
    ]
    for p in kern:
        lines.append(f"    {{{p[0]}, {p[1]}, {p[2]}}},   /* {chr(p[0])}{chr(p[1])} */".replace("\\", "backslash"))
    lines.append("};")
    lines.append(f"#define FONT_MID_NKERN {len(kern)}u")
    lines.append(f"static const uint8_t FONT_MID[{LAST - FIRST + 1}][{GW * CH}] = {{")
    for code, row in zip(range(FIRST, LAST + 1), g):
        lines.append("    {" + ",".join(str(v) for v in row) + "},   /* " + (chr(code) if chr(code) != "\\" else "backslash") + " */")
    lines.append("};")
    open("firmware/src/font_mid.c", "w").write("\n".join(lines) + "\n")
    print(f"firmware/src/font_mid.c: {len(g)} glyphs of {GW}x{CH}, {len(kern)} kerning pairs")


main()
